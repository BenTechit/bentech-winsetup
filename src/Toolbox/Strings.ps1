# src/Toolbox/Strings.ps1
# The BenTech Toolbox's string table (toolbox spec 4.3): every fixed text of the window, in English and Hebrew,
# under the same keys. The window's TextBlocks name their key in Tag="t:<key>"; Set-ToolboxLanguage (Toolbox.ps1)
# fills them from New-ToolboxStringTable, which adds the keys that come from config.json: profile.<id>,
# tweak.<id>.title and tweak.<id>.desc. {0} and {1} are format arguments.
#
# This is the ONLY src file allowed to contain non-ASCII (UTF-8 with BOM, as every .ps1; tests\Encoding.Tests.ps1
# checks every other src file is ASCII). Nothing here reaches setup.log, the console or the report: those stay
# English and ASCII, and Choices hold ASCII ids only. No Hebrew string contains an apostrophe (these are
# single-quoted strings).
#
# step.<id> names every step of the catalog (Engine\Catalog.ps1) for the window's "What will happen" column
# (ruling TB-R5): the English one is exactly the catalog's Title (tests\Toolbox.Tests.ps1 pins it); the console,
# setup.log and the report keep reading the catalog's English titles.
#
# finding.<Code> (Repair & diagnostics, repair plan "Findings"): the action child (src\Repair\ToolEngine.ps1) formats the
# English text into result.json (Get-ToolText); the window shows the language's text with the same Args.
#
# The Repair & diagnostics page (repair plan, "The string table additions"): nav.repair, the row labels, the tiles
# (tile.<id>.title / .line / .what, and .changes: the confirmation's list, one change per line), the chips and
# their tooltips, the confirmation, run and result panels, the gates' reasons and warnings, and tool.step.<id>: a
# name for every step of the action catalog (the English one is also the child's, Get-ToolStepName).
#
# Hebrew and bidi: a Hebrew line is shown right-to-left, so Latin words and numbers inside it are fine, but a Latin
# word right before an opening bracket would split the brackets ("Windows (DISM)"): those lines put a Hebrew word
# before the bracket instead. Machine values in a Hebrew line read left-to-right (ruling RD-R14): the repair page
# puts a left-to-right mark (U+200E) on both sides of every {n} value that is not Hebrew and not a plain number
# (Format-RepairText, RepairPage.ps1); a value written into a Hebrew string itself is wrapped the same way here, as
# in chip.free.level and step.7zip. WPF does not honour the isolate marks (U+2066..U+2069), only U+200E. The Hebrew
# chips name a drive by its letter alone ({2} / {1}): in a right-to-left line the colon of "E:" is met first.
